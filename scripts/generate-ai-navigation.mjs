import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const output = path.join(root, 'src', 'ai', 'generated');
const ruleCount = 190;
const rulesPerPack = 8;
const roles = ['melee', 'ranged', 'boss'];
const states = ['alert', 'chase', 'engage', 'investigate', 'search', 'return', 'patrol', 'idle'];
const styles = ['advance', 'flank-left', 'flank-right', 'orbit', 'retreat', 'anchor'];

fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output, { recursive: true });

function write(relative, source) {
  const target = path.join(output, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, source.endsWith('\n') ? source : `${source}\n`);
}

function fixed(value) {
  return Number(value.toFixed(4));
}

write('types.ts', `// Auto-generated by scripts/generate-ai-navigation.mjs.
export type GeneratedEnemyRole = 'melee' | 'ranged' | 'boss';
export type GeneratedAwarenessState = 'idle' | 'patrol' | 'alert' | 'chase' | 'engage' | 'investigate' | 'search' | 'return';
export type TacticalStyle = 'advance' | 'flank-left' | 'flank-right' | 'orbit' | 'retreat' | 'anchor';

export interface GeneratedPoint {
  x: number;
  y: number;
}

export interface GeneratedTacticalContext {
  actorId: number;
  role: GeneratedEnemyRole;
  state: GeneratedAwarenessState;
  self: GeneratedPoint;
  target: GeneratedPoint;
  home: GeneratedPoint;
  healthRatio: number;
  targetVisible: boolean;
  nearbyAllies: number;
  nearbyEnemies: number;
  routeCost: number;
  hazard: number;
  elapsed: number;
}

export interface GeneratedTacticalDecision {
  ruleId: string;
  score: number;
  destination: GeneratedPoint;
  speedScale: number;
  separationScale: number;
  holdPosition: boolean;
  preferredRange: number;
  style: TacticalStyle;
  reason: string;
}

export interface GeneratedTacticalRule {
  readonly id: string;
  readonly role: GeneratedEnemyRole;
  readonly state: GeneratedAwarenessState;
  readonly style: TacticalStyle;
  supports(context: GeneratedTacticalContext): boolean;
  evaluate(context: GeneratedTacticalContext): GeneratedTacticalDecision;
}

export function generatedClamp(value: number, minimum: number, maximum: number): number {
  return Math.max(minimum, Math.min(maximum, value));
}

export function generatedNormalize(point: GeneratedPoint): GeneratedPoint {
  const length = Math.hypot(point.x, point.y);
  if (length <= Number.EPSILON) return { x: 0, y: 0 };
  return { x: point.x / length, y: point.y / length };
}

export function generatedDistance(left: GeneratedPoint, right: GeneratedPoint): number {
  return Math.hypot(right.x - left.x, right.y - left.y);
}

export function generatedHash(value: number): number {
  let hash = value | 0;
  hash = Math.imul(hash ^ (hash >>> 16), 0x45d9f3b);
  hash = Math.imul(hash ^ (hash >>> 16), 0x45d9f3b);
  return (hash ^ (hash >>> 16)) >>> 0;
}

export function generatedNoise(seed: number): number {
  return generatedHash(seed) / 0xffffffff;
}

export function generatedRotate(point: GeneratedPoint, radians: number): GeneratedPoint {
  const cosine = Math.cos(radians);
  const sine = Math.sin(radians);
  return {
    x: point.x * cosine - point.y * sine,
    y: point.x * sine + point.y * cosine,
  };
}

export function generatedFallback(context: GeneratedTacticalContext): GeneratedTacticalDecision {
  return {
    ruleId: 'generated-fallback',
    score: 0,
    destination: { ...context.target },
    speedScale: 1,
    separationScale: 1,
    holdPosition: false,
    preferredRange: 96,
    style: 'advance',
    reason: 'No generated tactical policy accepted the current context.',
  };
}
`);

function classSource(index) {
  const padded = String(index + 1).padStart(4, '0');
  const role = roles[index % roles.length];
  const state = states[Math.floor(index / roles.length) % states.length];
  const style = styles[Math.floor(index / (roles.length * states.length)) % styles.length];
  const desiredRange = 64 + (index * 17) % 280;
  const lateralBias = fixed(((index % 13) - 6) / 8);
  const aggression = fixed(0.55 + (index % 19) * 0.027);
  const cohesion = fixed(0.2 + (index % 11) * 0.061);
  const hazardWeight = fixed(0.45 + (index % 7) * 0.19);
  const healthThreshold = fixed(0.2 + (index % 6) * 0.11);
  const phase = fixed((index % 32) * Math.PI / 16);
  const stride = 48 + (index * 23) % 160;
  return `export class TacticalRule${padded} implements GeneratedTacticalRule {
  public readonly id = 'tactical-rule-${padded}';
  public readonly role: GeneratedTacticalRule['role'] = '${role}';
  public readonly state: GeneratedTacticalRule['state'] = '${state}';
  public readonly style: GeneratedTacticalRule['style'] = '${style}';
  private readonly desiredRange = ${desiredRange};
  private readonly lateralBias = ${lateralBias};
  private readonly aggression = ${aggression};
  private readonly cohesion = ${cohesion};
  private readonly hazardWeight = ${hazardWeight};
  private readonly healthThreshold = ${healthThreshold};
  private readonly phase = ${phase};
  private readonly stride = ${stride};

  public supports(context: GeneratedTacticalContext): boolean {
    if (context.role !== this.role) return false;
    if (context.state === this.state) return true;
    if (this.state === 'chase' && context.state === 'investigate') return true;
    if (this.state === 'engage' && context.state === 'alert') return context.targetVisible;
    return false;
  }

  public evaluate(context: GeneratedTacticalContext): GeneratedTacticalDecision {
    const offset = { x: context.self.x - context.target.x, y: context.self.y - context.target.y };
    const distance = Math.max(0.001, generatedDistance(context.self, context.target));
    const radial = generatedNormalize(offset);
    const tangentSign = this.style === 'flank-left' ? -1 : this.style === 'flank-right' ? 1 : this.lateralBias >= 0 ? 1 : -1;
    const tangent = { x: -radial.y * tangentSign, y: radial.x * tangentSign };
    const healthPressure = generatedClamp((this.healthThreshold - context.healthRatio) * 2.2, -1, 1);
    const rangeError = generatedClamp((distance - this.desiredRange) / Math.max(32, this.desiredRange), -1.5, 1.5);
    const allyPressure = generatedClamp(context.nearbyAllies / 8, 0, 1);
    const routePressure = generatedClamp(context.routeCost / 900, 0, 1);
    const hazardPressure = generatedClamp(context.hazard, 0, 1) * this.hazardWeight;
    const pulse = Math.sin(context.elapsed * 0.001 + this.phase + context.actorId * 0.37);
    const retreatIntent = this.style === 'retreat' ? 1 : healthPressure > 0.2 ? healthPressure : 0;
    const advanceIntent = this.style === 'advance' ? this.aggression : generatedClamp(rangeError, 0, 1) * this.aggression;
    const orbitIntent = this.style === 'orbit' ? 0.9 : Math.abs(this.lateralBias) * 0.45;
    const anchorIntent = this.style === 'anchor' ? 1 : 0;
    const radialDistance = this.desiredRange + retreatIntent * this.stride - advanceIntent * this.stride * 0.45;
    const lateralDistance = (orbitIntent + allyPressure * this.cohesion) * this.stride * (0.65 + pulse * 0.15);
    const destination = {
      x: context.target.x + radial.x * radialDistance + tangent.x * lateralDistance,
      y: context.target.y + radial.y * radialDistance + tangent.y * lateralDistance,
    };
    const visibilityScore = context.targetVisible ? 0.24 : -0.08;
    const rangeScore = 1 - Math.min(1, Math.abs(distance - this.desiredRange) / Math.max(1, this.desiredRange));
    const formationScore = generatedClamp(1 - Math.abs(context.nearbyAllies - ${index % 5}) * 0.16, 0, 1);
    const safetyScore = generatedClamp(1 - hazardPressure - routePressure * 0.35, 0, 1);
    const score = generatedClamp(rangeScore * 0.36 + formationScore * 0.2 + safetyScore * 0.24 + visibilityScore + this.aggression * 0.12, -1, 2);
    const speedScale = generatedClamp(0.72 + advanceIntent * 0.35 + retreatIntent * 0.28 - routePressure * 0.12, 0.55, 1.45);
    const separationScale = generatedClamp(0.65 + allyPressure * this.cohesion + Math.abs(pulse) * 0.16, 0.5, 1.6);
    const holdPosition = anchorIntent > 0 && Math.abs(rangeError) < 0.24 && context.targetVisible;
    return {
      ruleId: this.id,
      score,
      destination: holdPosition ? { ...context.self } : destination,
      speedScale,
      separationScale,
      holdPosition,
      preferredRange: this.desiredRange,
      style: this.style,
      reason: this.explain(distance, rangeError, hazardPressure, context.targetVisible),
    };
  }

  private explain(distance: number, rangeError: number, hazardPressure: number, visible: boolean): string {
    const rangeLabel = rangeError > 0.2 ? 'closing' : rangeError < -0.2 ? 'creating-distance' : 'holding-range';
    const safetyLabel = hazardPressure > 0.45 ? 'avoiding-hazard' : 'safe-ground';
    const sightLabel = visible ? 'visual-contact' : 'memory-contact';
    return [this.style, rangeLabel, safetyLabel, sightLabel, Math.round(distance)].join(':');
  }
}`;
}

const packNames = [];
for (let start = 0; start < ruleCount; start += rulesPerPack) {
  const packNumber = Math.floor(start / rulesPerPack) + 1;
  const packName = `TacticalRulePack${String(packNumber).padStart(2, '0')}`;
  packNames.push(packName);
  const classNames = [];
  const blocks = [];
  for (let index = start; index < Math.min(ruleCount, start + rulesPerPack); index++) {
    classNames.push(`TacticalRule${String(index + 1).padStart(4, '0')}`);
    blocks.push(classSource(index));
  }
  write(`rules/${packName}.ts`, `// Auto-generated tactical rule pack.
import {
  GeneratedTacticalContext,
  GeneratedTacticalDecision,
  GeneratedTacticalRule,
  generatedClamp,
  generatedDistance,
  generatedNormalize,
} from '../types';

${blocks.join('\n\n')}

export const ${packName}: readonly GeneratedTacticalRule[] = [
${classNames.map((name) => `  new ${name}(),`).join('\n')}
];
`);
}

const imports = packNames.map((name) => `import { ${name} } from './rules/${name}';`).join('\n');
const spreads = packNames.map((name) => `  ...${name},`).join('\n');
write('catalog.ts', `// Auto-generated tactical catalog.
import { GeneratedTacticalRule } from './types';
${imports}

export const GENERATED_TACTICAL_RULES: readonly GeneratedTacticalRule[] = [
${spreads}
];

export const GENERATED_TACTICAL_RULE_COUNT = GENERATED_TACTICAL_RULES.length;
`);

write('GeneratedTacticalDirector.ts', `import { GENERATED_TACTICAL_RULES } from './catalog';
import {
  GeneratedTacticalContext,
  GeneratedTacticalDecision,
  GeneratedTacticalRule,
  generatedFallback,
  generatedHash,
} from './types';

export interface TacticalDirectorDiagnostics {
  evaluations: number;
  accepted: number;
  rejected: number;
  lastRuleId?: string;
}

export class GeneratedTacticalDirector {
  private evaluations = 0;
  private accepted = 0;
  private rejected = 0;
  private lastRuleId?: string;

  public constructor(private readonly rules: readonly GeneratedTacticalRule[] = GENERATED_TACTICAL_RULES) {
    if (rules.length === 0) throw new RangeError('generated tactical director requires at least one rule');
  }

  public decide(context: GeneratedTacticalContext): GeneratedTacticalDecision {
    const candidates = this.candidates(context);
    let best: GeneratedTacticalDecision | undefined;
    for (const rule of candidates) {
      this.evaluations++;
      if (!rule.supports(context)) {
        this.rejected++;
        continue;
      }
      this.accepted++;
      const decision = rule.evaluate(context);
      if (!best || decision.score > best.score || (decision.score === best.score && decision.ruleId < best.ruleId)) {
        best = decision;
      }
    }
    const result = best ?? generatedFallback(context);
    this.lastRuleId = result.ruleId;
    return result;
  }

  public diagnostics(): TacticalDirectorDiagnostics {
    return {
      evaluations: this.evaluations,
      accepted: this.accepted,
      rejected: this.rejected,
      lastRuleId: this.lastRuleId,
    };
  }

  public resetDiagnostics(): void {
    this.evaluations = 0;
    this.accepted = 0;
    this.rejected = 0;
    this.lastRuleId = undefined;
  }

  private candidates(context: GeneratedTacticalContext): GeneratedTacticalRule[] {
    const roleOffset = context.role === 'melee' ? 11 : context.role === 'ranged' ? 97 : 211;
    const stateOffset = context.state.length * 23;
    const spatialOffset = Math.floor(context.self.x / 32) * 17 + Math.floor(context.self.y / 32) * 31;
    const seed = generatedHash(context.actorId * 131 + roleOffset + stateOffset + spatialOffset);
    const result: GeneratedTacticalRule[] = [];
    const seen = new Set<number>();
    for (let probe = 0; probe < 72 && result.length < 18; probe++) {
      const index = generatedHash(seed + probe * 0x9e3779b1) % this.rules.length;
      if (seen.has(index)) continue;
      seen.add(index);
      const rule = this.rules[index];
      if (rule.role === context.role && (rule.state === context.state || rule.state === 'chase' || rule.state === 'engage')) {
        result.push(rule);
      }
    }
    if (result.length === 0) {
      for (const rule of this.rules) {
        if (rule.role === context.role && rule.state === context.state) result.push(rule);
        if (result.length >= 18) break;
      }
    }
    return result;
  }
}
`);

write('index.ts', `export * from './types';
export * from './catalog';
export * from './GeneratedTacticalDirector';
`);

console.log(`Generated ${ruleCount} executable tactical rules in ${packNames.length} packs.`);

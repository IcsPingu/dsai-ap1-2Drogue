export function getEnemyById(id: string): EnemyDefinition | undefined {
  return ALL_ENEMIES.find((e) => e.id === id);
}

export function getEnemiesByHierarchy(hierarchy: string): EnemyDefinition[] {
  return ALL_ENEMIES.filter((e) => e.hierarchy === hierarchy);
}

export function getBossEnemies(): EnemyDefinition[] {
  return ALL_ENEMIES.filter((e) => e.hierarchy === 'cardinal_virtue' || e.hierarchy === 'auditio');
}

export function getRandomEnemy(maxDifficulty: number): EnemyDefinition {
  const pool = ALL_ENEMIES.filter((e) => e.hierarchy !== 'cardinal_virtue' && e.hierarchy !== 'auditio');
  const filtered = pool.filter((e) => e.baseHealth <= maxDifficulty * 50);
  return filtered[Math.floor(Math.random() * filtered.length)] || ENEMY_AFFINITY;
}

// src/data/EnemyDatabase.ts
// Complete bestiary of all angel enemies, inspired by Bayonetta's hierarchy of Laguna.
// Each entry includes stats, behavior patterns, attack definitions, visual properties, and lore.

export interface AttackPattern {
  name: string;
  damage: number;
  range: number;
  windupMs: number;
  cooldownMs: number;
  hitboxWidth: number;
  hitboxHeight: number;
  knockback: number;
  canBeParried: boolean;
  projectile?: {
    speed: number;
    lifetime: number;
    piercing: boolean;
    texture: string;
  };
}

export interface EnemyBehavior {
  aiType: 'patrol' | 'chase' | 'ranged' | 'support' | 'boss_phase' | 'berserker' | 'ambush';
  aggroRange: number;
  deaggroRange: number;
  preferredDistance: number;
  fleeHealthPercent: number;
  canDodge: boolean;
  dodgeChance: number;
  canBlock: boolean;
  blockChance: number;
  canTeleport: boolean;
  teleportCooldownMs: number;
  summonAbility?: {
    summonType: string;
    maxSummons: number;
    summonCooldownMs: number;
  };
}

export interface EnemyVisuals {
  baseColor: number;
  glowColor: number;
  width: number;
  height: number;
  trailColor?: number;
  trailLength?: number;
  deathParticleColor: number;
  deathParticleCount: number;
  hitFlashColor: number;
  idleAnimFrames: number;
  walkAnimFrames: number;
  attackAnimFrames: number;
  deathAnimFrames: number;
  shadowScale: number;
  shadowAlpha: number;
}

export interface EnemyDefinition {
  id: string;
  name: string;
  title: string;
  description: string;
  lore: string;
  hierarchy: 'third_sphere' | 'second_sphere' | 'first_sphere' | 'cardinal_virtue' | 'auditio';
  baseHealth: number;
  healthPerLevel: number;
  baseDamage: number;
  damagePerLevel: number;
  baseSpeed: number;
  baseArmor: number;
  armorPerLevel: number;
  experienceValue: number;
  haloValue: number;
  attacks: AttackPattern[];
  behavior: EnemyBehavior;
  visuals: EnemyVisuals;
  resistances: {
    physical: number;
    fire: number;
    ice: number;
    lightning: number;
    dark: number;
    holy: number;
  };
  weaknesses: string[];
  immunities: string[];
  dropTable: { itemId: string; chance: number; minQuantity: number; maxQuantity: number }[];
}

